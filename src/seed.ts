const hoje = new Date();
function diaMais(n: number): string {
  const d = new Date(hoje);
  d.setDate(d.getDate() + n);
  return d.toISOString().slice(0, 10);
}
function horaAtras(h: number): string {
  const d = new Date(hoje);
  d.setHours(d.getHours() - h);
  return d.toISOString();
}

